"""Small dependency-inversion ports used by services and use cases."""

from datetime import datetime
from typing import Any, Protocol
from uuid import UUID

from .enums import ConfirmationStatus, ReportReason, ReportStatus


class UserRepositoryPort(Protocol):
    async def upsert_telegram_profile(
        self, tg_id: int, tg_name: str | None, tg_username: str | None
    ) -> Any: ...
    async def get_by_id(self, user_id: str) -> Any | None: ...
    async def get_by_telescan_id(self, telescan_id: UUID) -> Any | None: ...
    async def get_by_tg_id(self, tg_id: int) -> Any | None: ...
    async def update_photo(self, user_id: str, photo_url: str | None) -> Any: ...
    async def delete(self, user_id: str) -> None: ...


class LinkCodeRepositoryPort(Protocol):
    async def revoke_issued(self, user_id: str, now: datetime) -> None: ...
    async def create(
        self, code_hash: str, user_id: str, now: datetime, expires_at: datetime
    ) -> Any: ...
    async def consume(
        self, code_hash: str, device_id: UUID, now: datetime
    ) -> Any | None: ...
    async def delete_for_user(self, user_id: str) -> None: ...


class ReviewCodeRepositoryPort(Protocol):
    async def consume(
        self, code_hash: str, device_id: UUID, now: datetime
    ) -> Any | None: ...
    async def delete_for_user(self, user_id: str) -> None: ...


class SessionRepositoryPort(Protocol):
    async def create_or_replace(
        self, user_id: str, device_id: UUID, now: datetime, expires_at: datetime
    ) -> Any: ...
    async def set_refresh_hash(
        self, session_id: str, refresh_hash: str, now: datetime
    ) -> None: ...
    async def get_active(self, session_id: str, now: datetime) -> Any | None: ...
    async def rotate_refresh_hash(
        self, session_id: str, expected_hash: str, new_hash: str, now: datetime
    ) -> bool: ...
    async def revoke(self, session_id: str, now: datetime) -> None: ...
    async def revoke_all(self, user_id: str, now: datetime) -> None: ...
    async def delete_for_user(self, user_id: str) -> None: ...


class ConfirmationRepositoryPort(Protocol):
    async def create_logout_all(
        self, user_id: str, now: datetime, expires_at: datetime
    ) -> Any: ...
    async def register_message(
        self, confirmation_id: UUID, chat_id: int, message_id: int
    ) -> Any | None: ...
    async def decide(
        self,
        confirmation_id: UUID,
        user_id: str,
        status: ConfirmationStatus,
        now: datetime,
    ) -> Any | None: ...
    async def expire(
        self, confirmation_id: UUID, user_id: str, now: datetime
    ) -> Any | None: ...
    async def get_for_user(self, confirmation_id: UUID, user_id: str) -> Any | None: ...
    async def list_pending(self) -> list[Any]: ...
    async def delete_for_user(self, user_id: str) -> None: ...


class ReportRepositoryPort(Protocol):
    async def create(
        self,
        reporter: Any,
        target: Any,
        client_request_id: UUID,
        reason: ReportReason,
        details: str | None,
        now: datetime,
    ) -> Any: ...
    async def get_by_public_id(self, report_id: UUID) -> Any | None: ...
    async def list_by_status(
        self, status: ReportStatus | None, limit: int
    ) -> list[Any]: ...
    async def update_status(
        self,
        report_id: UUID,
        status: ReportStatus,
        moderator_id: str,
        note: str | None,
        now: datetime,
    ) -> Any | None: ...
    async def anonymize_user(self, user_id: str) -> None: ...


class BlockRepositoryPort(Protocol):
    async def create(self, blocker_id: str, target: Any, now: datetime) -> Any: ...
    async def delete(self, blocker_id: str, blocked_telescan_id: UUID) -> bool: ...
    async def exists_between(self, first_user_id: str, second_user_id: str) -> bool: ...
    async def list_for_user(self, blocker_id: str) -> list[Any]: ...
    async def delete_for_user(self, user_id: str) -> None: ...


class PhotoStoragePort(Protocol):
    async def upload(self, data: bytes, object_name: str, content_type: str) -> str: ...
    async def delete_by_url(self, public_url: str) -> None: ...
    async def delete_user_prefix(self, telescan_id: UUID) -> None: ...


class BotGatewayPort(Protocol):
    async def request_logout_all_confirmation(
        self, confirmation_id: UUID, chat_id: int, expires_at: datetime
    ) -> None: ...


class LegacyCodeRepositoryPort(Protocol):
    async def set_code_hash(self, user_id: str, code_hash: str) -> None: ...


class LegacyCodePublisherPort(Protocol):
    async def publish(self, user_id: str, clear_code: str) -> None: ...
